  <h1>Privacy Policy</h1>
  <p class="muted">Effective July 26, 2026</p>
  <p>PanicMic provides karaoke show-management tools to KJs. This policy explains the information processed when you operate or use a PanicMic show.</p>

  <h2>Information we collect</h2>
  <p>We process KJ and team account details such as name, email address, role, subscription status, and password hashes. Show data can include venues, schedules, catalog entries, display configuration, singer display names, song requests, request notes, and show history. We also collect security and operational logs such as IP address, browser information, request path, and error details.</p>

  <h2>How we use information</h2>
  <p>We use this information to provide and secure the service, synchronize live show controls, process account and billing changes, send transactional messages, troubleshoot failures, enforce limits, and improve reliability.</p>

  <h2>Service providers</h2>
  <p>Depending on configuration, PanicMic may use payment, email-delivery, video, music-metadata, and error-reporting providers. Those providers receive only the information needed to perform their service. KJs are responsible for ensuring they have appropriate rights to media and catalog data they upload or link.</p>

  <h2>Retention and deletion</h2>
  <p>We retain account and show data while an account is active and as reasonably needed for security, legal, billing, backup, and dispute-resolution purposes. Account owners can request export or deletion by contacting us. Some records may remain in backups for a limited period or where retention is legally required.</p>

  <h2>Your choices</h2>
  <p>You may ask to access, correct, export, or delete personal information associated with your account. Singers should ordinarily contact the KJ who operated the show; account-level requests can be sent to <a href="mailto:privacy@panicmic.com">privacy@panicmic.com</a>.</p>

  <h2>Security and changes</h2>
  <p>We use technical and organizational safeguards designed to protect information, but no system can guarantee absolute security. We may update this policy as the service changes and will post the revised effective date here.</p>
